def set_language(language: str) -> None:
    global _LANGUAGE
    _LANGUAGE = language if language in {"system", "ru", "en"} else "system"


def current_language() -> str:
    if _LANGUAGE != "system":
        return _LANGUAGE
    system_locale = locale.getlocale()[0] or ""
    return "en" if system_locale.lower().startswith("en") else "ru"


def tr(text: str) -> str:
    if current_language() == "en":
        return _ENGLISH.get(text, text)
    return text
